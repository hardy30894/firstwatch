use std::path::Path;
use std::process::Command;

use anyhow::{bail, Context, Result};
use firstwatch_mend::MendOutcome;
use firstwatch_prove::Verdict;
use firstwatch_schema::Severity;

pub struct PrArgs<'a> {
    pub root: &'a Path,
    pub branch: Option<String>,
    pub draft: bool,
    pub allow_unproven: bool,
}

pub fn open_pr(args: PrArgs, outcome: &MendOutcome, verdict: Option<&Verdict>) -> Result<()> {
    let root = args.root;
    ensure_clean_worktree(root)?;

    let proven = verdict.map(|v| v.proven).unwrap_or(false);
    if !proven && !args.allow_unproven {
        bail!("patches are unproven and --allow-unproven was not given");
    }

    let provider = outcome
        .patches
        .first()
        .map(|p| p.impact.change.provider.clone())
        .unwrap_or_else(|| "upstream".into());
    let branch = args
        .branch
        .unwrap_or_else(|| format!("firstwatch/{provider}-fixes"));

    git(root, &["checkout", "-b", &branch])?;
    firstwatch_mend::apply(root, &outcome.patches)?;
    git(root, &["add", "-A"])?;

    let title = format!(
        "Fix {} {} call site(s) impacted by upstream changes",
        outcome.patches.len(),
        provider
    );
    let body = pr_body(outcome, verdict);
    git(root, &["commit", "-m", &title, "-m", &body])?;

    if git(root, &["push", "-u", "origin", &branch]).is_err() {
        println!("firstwatch: committed on branch {branch}, push failed or no remote.");
        println!("push and open a PR manually when ready.");
        return Ok(());
    }

    let mut gh_args = vec!["pr", "create", "--title", &title, "--body", &body];
    if args.draft {
        gh_args.push("--draft");
    }
    let gh = Command::new("gh").args(&gh_args).current_dir(root).output();
    match gh {
        Ok(out) if out.status.success() => {
            print!("{}", String::from_utf8_lossy(&out.stdout));
            println!("firstwatch: PR opened from {branch}.");
        }
        _ => {
            println!(
                "firstwatch: pushed {branch}, gh unavailable or failed. Open the PR manually."
            );
        }
    }
    Ok(())
}

fn pr_body(outcome: &MendOutcome, verdict: Option<&Verdict>) -> String {
    let mut body = String::from("Generated by firstwatch. Every patch below was ");
    match verdict {
        Some(v) if v.proven => {
            body.push_str("applied to a staged copy and proven by:\n");
            for check in &v.checks {
                body.push_str(&format!("- {} passed\n", check.name));
            }
        }
        _ => body.push_str("proposed without proof (no verifiers detected).\n"),
    }
    body.push_str("\n## Patches\n");
    for patch in &outcome.patches {
        let change = &patch.impact.change;
        body.push_str(&format!(
            "- `{}:{}` {} ({:?}{})",
            patch.file,
            patch.line,
            patch.impact.site.surface,
            change.kind,
            change
                .effective_version
                .as_deref()
                .map(|v| format!(", effective {v}"))
                .unwrap_or_default()
        ));
        if let Some(url) = &change.evidence_url {
            body.push_str(&format!(" [evidence]({url})"));
        }
        body.push('\n');
    }
    if !outcome.refusals.is_empty() {
        body.push_str("\n## Needs human attention\n");
        for refusal in &outcome.refusals {
            let severity = match refusal.impact.severity {
                Severity::BreaksNow => "breaks now",
                Severity::BreaksLater => "breaks later",
                Severity::Deprecated => "deprecated",
                Severity::Opportunity => "new capability",
            };
            body.push_str(&format!(
                "- `{}:{}` {} ({severity}): {}\n",
                refusal.impact.site.file,
                refusal.impact.site.line,
                refusal.impact.site.surface,
                refusal.reason
            ));
        }
    }
    body
}

fn ensure_clean_worktree(root: &Path) -> Result<()> {
    let out = Command::new("git")
        .args(["status", "--porcelain"])
        .current_dir(root)
        .output()
        .context("running git status")?;
    if !out.status.success() {
        bail!("not a git repository: {}", root.display());
    }
    if !out.stdout.is_empty() {
        bail!("worktree has uncommitted changes, commit or stash them first");
    }
    Ok(())
}

fn git(root: &Path, args: &[&str]) -> Result<()> {
    let out = Command::new("git")
        .args(args)
        .current_dir(root)
        .output()
        .with_context(|| format!("running git {}", args.join(" ")))?;
    if !out.status.success() {
        bail!(
            "git {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(())
}
